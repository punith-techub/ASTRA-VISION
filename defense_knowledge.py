import re


def resolve_historical_metrics(
    name: str = "",
    designation: str = "",
    year_origin: str | None = None,
    number_built: str | None = None,
    operational_count: str | None = None,
    category: str = "",
    context_text: str = "",
) -> tuple[str, str, str]:
    """Dynamically parses and verifies historical year and production count for ANY open-world entity.
    Extracts authentic numeric data without domain bias, hardcoding, or platform favoritism.
    Rejects generic non-numeric placeholder strings (e.g. 'Modern', 'In production').
    """
    y = (year_origin or "").strip()
    b = (number_built or "").strip()
    op = (operational_count or "").strip()

    # Generic placeholder words to reject
    invalid_placeholders = {
        "modern", "modern era", "operational era", "unknown", "n/a", "none", "null", "—", "-",
        "in production", "serial", "serial production", "production volume", "various", "unspecified"
    }

    is_year_valid = bool(y) and (y.lower() not in invalid_placeholders) and bool(re.search(r"\d", y))
    is_built_valid = bool(b) and (b.lower() not in invalid_placeholders) and bool(re.search(r"\d", b))

    # If already authentic with numbers from the AI sensor, keep them as-is!
    if is_year_valid and is_built_valid:
        return y, b, op or "Active / Documented"

    # Search entity text and context for dynamic year extraction (any 4-digit historical or modern year: 1700-2030)
    corpus = f"{name} {designation} {context_text}".strip()
    if corpus:
        query = corpus.lower()
        # Check against indexed platforms if matching standard catalog
        for pid, p in DEFENSE_PLATFORMS.items():
            p_name = p.get("name", "").lower()
            p_desig = p.get("designation", "").lower()
            if pid in query or (len(p_name) > 4 and p_name in query) or (len(p_desig) >= 3 and p_desig in query):
                if not is_year_valid and p.get("year_origin"):
                    y = p["year_origin"]
                    is_year_valid = True
                if not is_built_valid and p.get("number_built"):
                    b = p["number_built"]
                    is_built_valid = True
                if not op and p.get("operational_count"):
                    op = p["operational_count"]
                break

        # Dynamically extract 4-digit year from the entity name/designation/context
        if not is_year_valid:
            year_match = re.search(r"\b(1[789]\d{2}|20[0-2]\d)\b", corpus)
            if year_match:
                y = f"{year_match.group(1)}"
                is_year_valid = True

    # If year or built count was not provided with numbers, leave as clean neutral string (never 'Modern' / 'In production')
    if not is_year_valid:
        y = "Historical / Contemporary"

    if not is_built_valid:
        b = "Documented Production"

    if not op:
        op = "Active / Documented"

    return y, b, op


def register_dynamic_platform(info: dict) -> None:
    """Dynamically ingests newly recognized platforms into the runtime intelligence base."""
    pid = info.get("id") or info.get("designation", "").lower().replace(" ", "-")
    if pid and pid not in DEFENSE_PLATFORMS:
        if "category" not in info:
            info["category"] = info.get("predicted_category", info.get("type", "object"))
        DEFENSE_PLATFORMS[pid] = info  # type: ignore


def get_platform(platform_id: str) -> PlatformInfo | None:
    return DEFENSE_PLATFORMS.get(platform_id)


def get_platforms_by_category(category: str) -> list[PlatformInfo]:
    return [p for p in DEFENSE_PLATFORMS.values() if p.get("category") == category]


def all_platforms() -> list[PlatformInfo]:
    return list(DEFENSE_PLATFORMS.values())




